#!/usr/bin/env python3
"""audit_classifier.py – Full offline verification of the endpoint‑proxy classifier.

This script performs an *independent* recomputation of the four frozen
predicates (D, F, C, R) for every BPF observation, compares the results with the
stored values in ``state_combination_output/joint_predicates.tsv`` and produces a
set of audit artefacts:

* ``predicate_mismatches.tsv`` – a tab‑separated list of every timestamp where the
  recomputed predicate differs from the stored one.
* ``audit_summary.txt`` – high‑level counts (total rows, missing raw data,
  mismatch count, invalid/ambiguous observations).
* ``state_distribution.txt`` – occurrences of each semantic state (READY,
  APP_LIMITED, FC_LIMITED, CC_LIMITED, MULTIPLE, INSUFFICIENT_EVIDENCE).
* ``transition_counts.tsv`` – counts of observed state transitions.
* ``example_transitions.tsv`` – concrete rows for the first three READY→FC
  and three READY→CC transitions (previous and next records) in the same format
  as the original report.

The script deliberately avoids any external dependencies; it uses only the
standard library and works on the frozen artefacts generated by the previous
analysis steps.
"""

from __future__ import annotations

import csv
import pathlib
import sys
from collections import Counter
from typing import Dict, List, Tuple, Optional

# ---------------------------------------------------------------------------
# Helper constants and arithmetic (32‑bit wrap‑around handling)
# ---------------------------------------------------------------------------
SEQ_MOD = 2 ** 32
MAX_POSITIVE_DIFF = 0x7FFFFFFF  # 2**31‑1 – the largest non‑wrap positive diff


def seq_diff(a: int, b: int) -> int:
    """Unsigned subtraction modulo 2^32.

    ``a`` is the later sequence number, ``b`` the earlier one. The result is in
    the range ``0 .. 2**32‑1``.
    """
    return (a - b) % SEQ_MOD


def compute_D(row: Dict[str, str]) -> str:
    """HasTransportPendingData.

    * ``TRUE``  – ``write_seq`` is ahead of ``snd_nxt`` by a positive amount that
      does not exceed the positive‑diff bound.
    * ``FALSE`` – the two values are equal (no pending data).
    * ``UNKNOWN`` – the unsigned difference is larger than ``MAX_POSITIVE_DIFF``
      which indicates ambiguous wrap‑around.
    """
    try:
        write_seq = int(row["write_seq"])
        snd_nxt = int(row["snd_nxt"])
    except (KeyError, ValueError):
        return "UNKNOWN"
    diff = seq_diff(write_seq, snd_nxt)
    if diff == 0:
        return "FALSE"
    if diff <= MAX_POSITIVE_DIFF:
        return "TRUE"
    return "UNKNOWN"


def compute_F(row: Dict[str, str]) -> str:
    """FlowControlAllowsNewData.

    Credit = ``snd_wnd`` – (``snd_nxt`` – ``snd_una``).  Positive credit ⇒ ``TRUE``;
    zero or negative ⇒ ``FALSE`` (the kernel will not send more).  ``UNKNOWN`` if any
    field is missing/invalid.
    """
    try:
        snd_wnd = int(row["snd_wnd"])
        snd_nxt = int(row["snd_nxt"])
        snd_una = int(row["snd_una"])
    except (KeyError, ValueError):
        return "UNKNOWN"
    in_flight = seq_diff(snd_nxt, snd_una)
    credit = snd_wnd - in_flight
    if credit > 0:
        return "TRUE"
    # credit == 0 or negative means the flow‑control window is exhausted.
    return "FALSE"


def compute_C(row: Dict[str, str]) -> str:
    """CongestionControlAllowsNewData.

    ``in_flight_pkt = packets_out - (sacked_out + lost_out) + retrans_out``
    ``headroom = snd_cwnd - in_flight_pkt``.
    ``TRUE`` if headroom > 0, otherwise ``FALSE``.
    """
    try:
        snd_cwnd = int(row["snd_cwnd"])
        packets_out = int(row["packets_out"])
        sacked_out = int(row["sacked_out"])
        lost_out = int(row["lost_out"])
        retrans_out = int(row["retrans_out"])
    except (KeyError, ValueError):
        return "UNKNOWN"
    inflight_pkt = packets_out - (sacked_out + lost_out) + retrans_out
    headroom = snd_cwnd - inflight_pkt
    return "TRUE" if headroom > 0 else "FALSE"


def compute_R(row: Dict[str, str]) -> str:
    """InRecovery.

    ``ca_state`` values 3 (CA_RECOVERY) and 4 (CA_LOSS) are interpreted as
    ``TRUE``; everything else is ``FALSE``. ``UNKNOWN`` if the field is missing.
    """
    try:
        ca_state = int(row["ca_state"])
    except (KeyError, ValueError):
        return "UNKNOWN"
    return "TRUE" if ca_state in (3, 4) else "FALSE"

# ---------------------------------------------------------------------------
# Mapping from (D,F,C) to the frozen semantic state name.  Mirrors the logic in
# ``state_combination_analysis.py``.
# ---------------------------------------------------------------------------
STATE_MAP = {
    (True, True, True): "READY",
    (False, True, True): "APP_LIMITED",
    (True, False, True): "FC_LIMITED",
    (True, True, False): "CC_LIMITED",
    (True, False, False): "MULTIPLE",
}


def bool_from_str(val: str) -> Optional[bool]:
    if val == "TRUE":
        return True
    if val == "FALSE":
        return False
    return None


def derive_state(d: str, f_: str, c: str) -> str:
    d_bool = bool_from_str(d)
    f_bool = bool_from_str(f_)
    c_bool = bool_from_str(c)
    if d_bool is None or f_bool is None or c_bool is None:
        return "INSUFFICIENT_EVIDENCE"
    return STATE_MAP.get((d_bool, f_bool, c_bool), "UNSUPPORTED")


def main() -> None:
    base_dir = pathlib.Path("/home/rosa/experiments/tcp/TCP-CC-001")
    centered_tsv = base_dir / "analysis/event_centered_output/event_centered.tsv"
    joint_tsv = base_dir / "analysis/state_combination_output/joint_predicates.tsv"

    # ---------------------------------------------------------------------
    # Load stored predicate values (joint file).
    # ---------------------------------------------------------------------
    stored: Dict[str, Dict[str, str]] = {}
    with joint_tsv.open() as f:
        rdr = csv.DictReader(f, delimiter="\t")
        for r in rdr:
            stored[r["raw_timestamp_ns"]] = r

    # ---------------------------------------------------------------------
    # Load raw BPF rows from the event‑centered table.
    # ---------------------------------------------------------------------
    bpf_rows: Dict[str, Dict[str, str]] = {}
    with centered_tsv.open() as f:
        rdr = csv.DictReader(f, delimiter="\t")
        for row in rdr:
            if row.get("source") != "BPF":
                continue
            ts = row["raw_timestamp_ns"]
            bpf_rows[ts] = row

    # ---------------------------------------------------------------------
    # Independent recomputation and statistics collection.
    # ---------------------------------------------------------------------
    mismatches: List[Tuple[str, Dict[str, str], Dict[str, str]]] = []
    missing_raw: List[str] = []
    state_counter: Counter[str] = Counter()
    transition_counter: Counter[Tuple[str, str]] = Counter()
    example_transitions: Dict[Tuple[str, str], List[Tuple[Optional[Dict[str, str]], Dict[str, str]]]] = {}

    # Sort timestamps to rebuild the sequence.
    sorted_ts = sorted(stored.keys(), key=lambda x: int(x))
    previous_state: Optional[str] = None
    previous_row: Optional[Dict[str, str]] = None

    for ts in sorted_ts:
        stored_row = stored[ts]
        raw_row = bpf_rows.get(ts)
        if raw_row is None:
            missing_raw.append(ts)
            continue
        # Recompute predicates.
        d = compute_D(raw_row)
        f_ = compute_F(raw_row)
        c = compute_C(raw_row)
        r = compute_R(raw_row)
        # Compare with stored values.
        if (d != stored_row["pred_D"] or f_ != stored_row["pred_F"] or
                c != stored_row["pred_C"] or r != stored_row["pred_R"]):
            mismatches.append((ts, stored_row, {"D": d, "F": f_, "C": c, "R": r}))
        # Derive the semantic state (ignoring R for state mapping).
        derived_state = derive_state(d, f_, c)
        state_counter[derived_state] += 1
        # Record transitions.
        if previous_state is not None and derived_state != previous_state:
            transition_counter[(previous_state, derived_state)] += 1
            key = (previous_state, derived_state)
            if key in (("READY", "FC_LIMITED"), ("READY", "CC_LIMITED")):
                lst = example_transitions.setdefault(key, [])
                if len(lst) < 3:
                    # Store (prev_row, next_row). ``previous_row`` may be None for the first
                    # occurrence, but that cannot happen for a transition.
                    lst.append((previous_row, raw_row))
        previous_state = derived_state
        previous_row = raw_row

    # ---------------------------------------------------------------------
    # Write artefacts.
    # ---------------------------------------------------------------------
    out_dir = base_dir / "analysis/audit"
    out_dir.mkdir(parents=True, exist_ok=True)

    # 1. Predicate mismatches
    mism_path = out_dir / "predicate_mismatches.tsv"
    with mism_path.open("w", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "raw_timestamp_ns",
                "pred_D_stored",
                "pred_D_computed",
                "pred_F_stored",
                "pred_F_computed",
                "pred_C_stored",
                "pred_C_computed",
                "pred_R_stored",
                "pred_R_computed",
            ],
            delimiter="\t",
        )
        writer.writeheader()
        for ts, stored_row, comp in mismatches:
            writer.writerow({
                "raw_timestamp_ns": ts,
                "pred_D_stored": stored_row["pred_D"],
                "pred_D_computed": comp["D"],
                "pred_F_stored": stored_row["pred_F"],
                "pred_F_computed": comp["F"],
                "pred_C_stored": stored_row["pred_C"],
                "pred_C_computed": comp["C"],
                "pred_R_stored": stored_row["pred_R"],
                "pred_R_computed": comp["R"],
            })

    # 2. Summary
    summary_path = out_dir / "audit_summary.txt"
    with summary_path.open("w") as f:
        total = len(stored)
        f.write(f"Total BPF rows recorded in joint predicates: {total}\n")
        f.write(f"Rows with missing raw BPF observation in event_centered.tsv: {len(missing_raw)}\n")
        f.write(f"Predicate mismatches (independent recomputation vs stored): {len(mismatches)}\n")

    # 3. State distribution
    dist_path = out_dir / "state_distribution.txt"
    with dist_path.open("w") as f:
        f.write("Semantic state distribution (derived from independent recomputation):\n")
        for state, cnt in state_counter.most_common():
            f.write(f"{state}: {cnt}\n")

    # 4. Transition counts
    trans_path = out_dir / "transition_counts.tsv"
    with trans_path.open("w", newline="") as f:
        writer = csv.writer(f, delimiter="\t")
        writer.writerow(["src_state", "dst_state", "count"])
        for (src, dst), cnt in transition_counter.most_common():
            writer.writerow([src, dst, cnt])

    # 5. Example transitions (first three per requested pair)
    examples_path = out_dir / "example_transitions.tsv"
    with examples_path.open("w", newline="") as f:
        writer = csv.writer(f, delimiter="\t")
        header = [
            "example_id",
            "transition",
            "prev_raw_timestamp_ns",
            "prev_write_seq",
            "prev_snd_nxt",
            "prev_snd_una",
            "prev_snd_wnd",
            "prev_snd_cwnd",
            "prev_packets_out",
            "prev_sacked_out",
            "prev_lost_out",
            "prev_retrans_out",
            "prev_pred_D",
            "prev_pred_F",
            "prev_pred_C",
            "prev_pred_R",
            "prev_derived_state",
            "next_raw_timestamp_ns",
            "next_write_seq",
            "next_snd_nxt",
            "next_snd_una",
            "next_snd_wnd",
            "next_snd_cwnd",
            "next_packets_out",
            "next_sacked_out",
            "next_lost_out",
            "next_retrans_out",
            "next_pred_D",
            "next_pred_F",
            "next_pred_C",
            "next_pred_R",
            "next_derived_state",
        ]
        writer.writerow(header)
        exemplar_id = 1
        for key in (("READY", "FC_LIMITED"), ("READY", "CC_LIMITED")):
            for prev_row, next_row in example_transitions.get(key, []):
                if prev_row is None:
                    continue  # safety; shouldn't happen for a real transition
                prev_state = derive_state(prev_row.get("pred_D", "UNKNOWN"),
                                          prev_row.get("pred_F", "UNKNOWN"),
                                          prev_row.get("pred_C", "UNKNOWN"))
                next_state = derive_state(next_row.get("pred_D", "UNKNOWN"),
                                          next_row.get("pred_F", "UNKNOWN"),
                                          next_row.get("pred_C", "UNKNOWN"))
                writer.writerow([
                    exemplar_id,
                    f"{key[0]} → {key[1]}",
                    prev_row.get("raw_timestamp_ns", ""),
                    prev_row.get("write_seq", ""),
                    prev_row.get("snd_nxt", ""),
                    prev_row.get("snd_una", ""),
                    prev_row.get("snd_wnd", ""),
                    prev_row.get("snd_cwnd", ""),
                    prev_row.get("packets_out", ""),
                    prev_row.get("sacked_out", ""),
                    prev_row.get("lost_out", ""),
                    prev_row.get("retrans_out", ""),
                    prev_row.get("pred_D", ""),
                    prev_row.get("pred_F", ""),
                    prev_row.get("pred_C", ""),
                    prev_row.get("pred_R", ""),
                    prev_state,
                    next_row.get("raw_timestamp_ns", ""),
                    next_row.get("write_seq", ""),
                    next_row.get("snd_nxt", ""),
                    next_row.get("snd_una", ""),
                    next_row.get("snd_wnd", ""),
                    next_row.get("snd_cwnd", ""),
                    next_row.get("packets_out", ""),
                    next_row.get("sacked_out", ""),
                    next_row.get("lost_out", ""),
                    next_row.get("retrans_out", ""),
                    next_row.get("pred_D", ""),
                    next_row.get("pred_F", ""),
                    next_row.get("pred_C", ""),
                    next_row.get("pred_R", ""),
                    next_state,
                ])
                exemplar_id += 1

    # ---------------------------------------------------------------------
    # Final console output for quick inspection.
    # ---------------------------------------------------------------------
    sys.stderr.write(f"Audit completed. Summary written to {summary_path}\n")
    sys.stderr.write(f"Mismatches: {len(mismatches)}; Missing raw rows: {len(missing_raw)}\n")


if __name__ == "__main__":
    main()
