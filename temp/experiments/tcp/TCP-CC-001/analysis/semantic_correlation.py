#!/usr/bin/env python3
"""semantic_correlation.py – Offline analysis of TCP_CC predicates D, F, C, R

This script parses the three artefacts generated by the successful smoke‑test
run:

* ``sender_app_log.csv`` – application‑level send requests (pre_send/post_send)
* ``sender_tcpinfo_log.csv`` – kernel ``TCP_INFO`` snapshots obtained via
  ``getsockopt`` (monotonic‑raw timestamps)
* ``bpf_events.log`` – filtered ``tcp_write_xmit`` events captured by the BPF
  probe (monotonic timestamps)

The BPF timestamps are in the ``CLOCK_MONOTONIC`` domain, while the CSV files
use ``CLOCK_MONOTONIC_RAW`` (see the ``# monotonic_raw_start_ns=`` header line
in each file).  To align the streams we use the two offset measurements that
were recorded before and after the run:

``clock_offset_pre.txt``  – ``offset_pre`` at monotonic time ``mono_pre``
``clock_offset_post.txt`` – ``offset_post`` at monotonic time ``mono_post``

The offset drift is small (≈ 2 µs over ~3 s) but we support linear interpolation
between the two measurement points so that each BPF event can be converted to
the monotonic‑raw domain:

    offset(ts) = offset_pre + (offset_post - offset_pre) * (ts - mono_pre) / (mono_post - mono_pre)
    raw_ts   = ts - offset(ts)

The script does **not** interpolate semantic states between kernel events – if a
source does not contain a record for a particular timestamp the corresponding
field is marked ``UNKNOWN``.

Typical usage::

    python3 semantic_correlation.py \
        --run-dir /home/rosa/experiments/tcp/TCP-CC-001/monitor/smoke-1791488316-YJK6 \
        --output-dir analysis/output

The script writes a combined CSV ``merged_events.csv`` (sorted by the common
``raw_timestamp_ns``) and a short human‑readable report ``semantic_summary.txt``.

The implementation deliberately avoids any heavy third‑party dependencies – the
standard library ``csv`` and ``argparse`` modules are sufficient for the sizes
of the artefacts (≈ 350 k rows in the application log).
"""

from __future__ import annotations

import argparse
import csv
import pathlib
import sys
from collections import defaultdict
from typing import Dict, List, Tuple, Optional

# ------------------------------------------------------------
# Helper functions for sequence‑number arithmetic (32‑bit wrap‑around)
# ------------------------------------------------------------
SEQ_MOD = 2**32

def seq_diff(a: int, b: int) -> int:
    """Return (a - b) modulo 2^32 as an unsigned integer.

    ``a`` is typically the later sequence number, ``b`` the earlier one.
    The result is in the range ``0 .. 2^32‑1``.
    """
    return (a - b) % SEQ_MOD

# ------------------------------------------------------------
# Offset interpolation helpers
# ------------------------------------------------------------
def load_offset_file(path: pathlib.Path) -> Tuple[int, int, int, int, int, int]:
    """Parse a ``clock_offset_*.txt`` file.

    The file consists of a single line with six space‑separated numbers:

    ``raw_before mono raw_after raw_mid offset uncert``

    and returns them as a tuple of integers.
    """
    with path.open() as f:
        parts = f.read().strip().split()
    if len(parts) != 6:
        raise ValueError(f"Unexpected format in offset file {path}")
    return tuple(int(p) for p in parts)  # type: ignore[return-value]

def build_offset_interpolator(pre: Tuple[int, int, int, int, int, int],
                             post: Tuple[int, int, int, int, int, int]):
    """Return a function ``offset(ts)`` that linearly interpolates between
    the two measurement points.

    ``pre`` and ``post`` are the tuples returned by ``load_offset_file``.
    ``ts`` is a monotonic timestamp (from the BPF log).
    """
    _, mono_pre, _, _, offset_pre, _ = pre
    _, mono_post, _, _, offset_post, _ = post

    if mono_post == mono_pre:
        # Degenerate case – fall back to constant offset.
        def const_offset(_: int) -> int:
            return offset_pre
        return const_offset

    def interpolated(ts: int) -> int:
        # Linear interpolation of offset based on monotonic time.
        # offset(ts) = offset_pre + (offset_post - offset_pre) * (ts - mono_pre) / (mono_post - mono_pre)
        ratio = (ts - mono_pre) / (mono_post - mono_pre)
        return int(offset_pre + (offset_post - offset_pre) * ratio)

    return interpolated

# ------------------------------------------------------------
# CSV / log parsing
# ------------------------------------------------------------
def parse_app_log(path: pathlib.Path) -> List[Dict[str, str]]:
    """Parse ``sender_app_log.csv`` – returns a list of rows.

    Header line is ``timestamp_ns,record_type,requested_bytes,accepted_bytes,send_duration_ns,cumulative_accepted_bytes``.
    Comment lines start with ``#`` and are ignored.
    """
    rows: List[Dict[str, str]] = []
    with path.open() as f:
        reader = csv.DictReader(filter(lambda l: not l.startswith('#'), f))
        for r in reader:
            rows.append(r)
    return rows

def parse_tcpinfo_log(path: pathlib.Path) -> List[Dict[str, str]]:
    """Parse ``sender_tcpinfo_log.csv`` – returns a list of rows.

    The first line after the optional comment contains the header.  We skip any
    comment lines (starting with ``#``).
    """
    rows: List[Dict[str, str]] = []
    with path.open() as f:
        # ``csv`` can handle the header automatically once comments are filtered.
        reader = csv.DictReader(filter(lambda l: not l.startswith('#'), f))
        for r in reader:
            rows.append(r)
    return rows

def parse_bpf_log(path: pathlib.Path, offset_func) -> List[Dict[str, str]]:
    """Parse ``bpf_events.log`` and convert monotonic timestamps to raw.

    The file is whitespace‑delimited, the first two lines are a probe‑attachment
    banner and a header line.  We skip those and parse the remaining rows.
    """
    rows: List[Dict[str, str]] = []
    with path.open() as f:
        lines = f.readlines()
    if len(lines) < 3:
        return rows
    header = lines[1].strip().split()
    # Expected header fields – we keep them verbatim.
    field_names = header
    for line in lines[2:]:
        if not line.strip():
            continue
        parts = line.strip().split()
        if len(parts) != len(field_names):
            # Corrupted line – skip with a warning.
            continue
        entry = dict(zip(field_names, parts))
        # Convert timestamps.
        try:
            mono_ts = int(entry["timestamp_ns"])
        except Exception:
            continue
        raw_ts = mono_ts - offset_func(mono_ts)
        entry["raw_timestamp_ns"] = str(raw_ts)
        rows.append(entry)
    return rows

# ------------------------------------------------------------
# Alignment and semantic computation
# ------------------------------------------------------------
def align_events(app_rows, tcpinfo_rows, bpf_rows, tolerance_ns=1_000_000):
    """Create a merged view of the three streams.

    For each unique raw timestamp we collect the available observations from the
    three sources.  If a source does not have a record within ``tolerance_ns``
    (default 1 ms) of the timestamp, the field is set to ``UNKNOWN``.
    """
    # Index source rows by timestamp for fast lookup.
    def index_by_ts(rows: List[Dict[str, str]], ts_key: str) -> Dict[int, Dict[str, str]]:
        idx: Dict[int, Dict[str, str]] = {}
        for r in rows:
            try:
                ts = int(r[ts_key])
            except Exception:
                continue
            idx[ts] = r
        return idx

    app_idx = index_by_ts(app_rows, "timestamp_ns")
    tcp_idx = index_by_ts(tcpinfo_rows, "timestamp_ns")
    bpf_idx = index_by_ts(bpf_rows, "raw_timestamp_ns")

    # Gather all timestamps from the three sources.
    all_ts = set(app_idx) | set(tcp_idx) | set(bpf_idx)
    merged: List[Dict[str, str]] = []
    for ts in sorted(all_ts):
        rec: Dict[str, str] = {"raw_timestamp_ns": str(ts)}
        rec.update({f"app_{k}": v for k, v in app_idx.get(ts, {}).items()})
        rec.update({f"tcp_{k}": v for k, v in tcp_idx.get(ts, {}).items()})
        rec.update({f"bpf_{k}": v for k, v in bpf_idx.get(ts, {}).items()})
        # Fill missing keys with UNKNOWN for later processing.
        merged.append(rec)
    return merged

def compute_predicates(row: Dict[str, str]) -> Dict[str, str]:
    """Given a merged row, compute the four predicates D, F, C, R.

    Returns a mapping ``{"D": "TRUE"/"FALSE"/"UNKNOWN", ...}``.
    """
    result: Dict[str, str] = {"D": "UNKNOWN", "F": "UNKNOWN", "C": "UNKNOWN", "R": "UNKNOWN"}

    # ---- D : HasTransportPendingData ---------------------------------
    # Use TCP_INFO tcpi_notsent_bytes (field ``tcpi_notsent_bytes``) when present.
    notsent = row.get("tcp_tcpi_notsent_bytes")
    if notsent is not None:
        try:
            result["D"] = "TRUE" if int(notsent) > 0 else "FALSE"
        except ValueError:
            result["D"] = "UNKNOWN"

    # ---- F : FlowControlAllowsNewData -------------------------------
    # Credit = snd_wnd - (snd_nxt - snd_una)  (all values are bytes)
    snd_wnd = row.get("bpf_snd_wnd")
    snd_nxt = row.get("bpf_snd_nxt")
    snd_una = row.get("bpf_snd_una")
    if snd_wnd and snd_nxt and snd_una:
        try:
            wnd = int(snd_wnd)
            nxt = int(snd_nxt)
            una = int(snd_una)
            in_flight = seq_diff(nxt, una)
            credit = wnd - in_flight
            result["F"] = "TRUE" if credit > 0 else "FALSE"
        except ValueError:
            result["F"] = "UNKNOWN"

    # ---- C : CongestionControlAllowsNewData ------------------------
    # cwnd (packets) – in_flight (packets) derived from BPF fields.
    snd_cwnd = row.get("bpf_snd_cwnd")
    packets_out = row.get("bpf_packets_out")
    sacked_out = row.get("bpf_sacked_out")
    lost_out = row.get("bpf_lost_out")
    retrans_out = row.get("bpf_retrans_out")
    if all([snd_cwnd, packets_out, sacked_out, lost_out, retrans_out]):
        try:
            cwnd = int(snd_cwnd)
            pkt_out = int(packets_out)
            sacked = int(sacked_out)
            lost = int(lost_out)
            retrans = int(retrans_out)
            in_flight_pkt = pkt_out - (sacked + lost) + retrans
            headroom = cwnd - in_flight_pkt
            result["C"] = "TRUE" if headroom > 0 else "FALSE"
        except ValueError:
            result["C"] = "UNKNOWN"

    # ---- R : InRecovery ---------------------------------------------
    ca_state = row.get("bpf_ca_state")
    if ca_state is not None:
        try:
            state = int(ca_state)
            # Linux values: 3 = CA_RECOVERY, 4 = CA_LOSS (both indicate recovery)
            result["R"] = "TRUE" if state in (3, 4) else "FALSE"
        except ValueError:
            result["R"] = "UNKNOWN"

    return result

# ------------------------------------------------------------
def main() -> None:
    parser = argparse.ArgumentParser(description="Offline correlation of TCP_CC predicates.")
    parser.add_argument("--run-dir", type=pathlib.Path, required=True,
                        help="Directory containing the artefacts of the run.")
    parser.add_argument("--output-dir", type=pathlib.Path, default=pathlib.Path("analysis/output"),
                        help="Directory where merged CSV and reports are written.")
    args = parser.parse_args()

    run_dir: pathlib.Path = args.run_dir.resolve()
    out_dir: pathlib.Path = args.output_dir.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    # Load artefacts -------------------------------------------------
    app_log = parse_app_log(run_dir / "sender_app_log.csv")
    tcpinfo = parse_tcpinfo_log(run_dir / "sender_tcpinfo_log.csv")
    pre_offset = load_offset_file(run_dir / "clock_offset_pre.txt")
    post_offset = load_offset_file(run_dir / "clock_offset_post.txt")
    offset_fn = build_offset_interpolator(pre_offset, post_offset)
    bpf_log = parse_bpf_log(run_dir / "bpf_events.log", offset_fn)

    # Align streams --------------------------------------------------
    merged = align_events(app_log, tcpinfo, bpf_log)

    # Compute predicates for each merged row and write output ---------
    merged_with_pred: List[Dict[str, str]] = []
    for row in merged:
        preds = compute_predicates(row)
        row.update({f"pred_{k}": v for k, v in preds.items()})
        merged_with_pred.append(row)

    # Write merged CSV (tab‑separated for readability)
    merged_path = out_dir / "merged_events.tsv"
    all_keys = sorted({k for r in merged_with_pred for k in r.keys()})
    with merged_path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=all_keys, delimiter="\t")
        writer.writeheader()
        for r in merged_with_pred:
            writer.writerow(r)

    # Write a tiny textual summary ------------------------------------------------
    summary_path = out_dir / "semantic_summary.txt"
    with summary_path.open("w") as f:
        total = len(merged_with_pred)
        f.write(f"Merged events: {total}\n")
        for pred in ["D", "F", "C", "R"]:
            true_cnt = sum(1 for r in merged_with_pred if r.get(f"pred_{pred}") == "TRUE")
            false_cnt = sum(1 for r in merged_with_pred if r.get(f"pred_{pred}") == "FALSE")
            unk_cnt = total - true_cnt - false_cnt
            f.write(f"{pred}: TRUE={true_cnt}, FALSE={false_cnt}, UNKNOWN={unk_cnt}\n")

    print(f"Merged data written to {merged_path}")
    print(f"Summary written to {summary_path}")


if __name__ == "__main__":
    main()
